def lookup(folder_name: str) -> Optional[str]:
    """按目录名查软件归属。"""
    key = normalize(folder_name)
    if not key:
        return None
    if key in SOFTWARE_MAP:
        return SOFTWARE_MAP[key]
    # 逐步放宽：去掉尾部数字/版本号
    trimmed = re.sub(r"\d+$", "", key)
    if trimmed and trimmed in SOFTWARE_MAP:
        return SOFTWARE_MAP[trimmed]
    # 前缀包含匹配（取最长 key）
    best: Optional[Tuple[int, str]] = None
    for k, v in SOFTWARE_MAP.items():
        if len(k) >= 4 and (k in key or key in k):
            score = len(k)
            if best is None or score > best[0]:
                best = (score, v)
    return best[1] if best else None


def company_of(text: str) -> str:
    """从文本中推测厂商。"""
    low = (text or "").lower()
    for k, v in COMPANY_HINTS.items():
        if k in low:
            return v
    return ""


def is_protected_dir(name: str) -> bool:
    return normalize(name) in {normalize(p) for p in PROTECTED_DIRS}


def looks_like_component(name: str) -> bool:
    low = (name or "").lower()
    return any(k in low for k in COMPONENT_KEYWORDS)
